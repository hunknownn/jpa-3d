                generated = "SEQUENCE", sequenceName = "user_seq")
        ))))
        val out = DdlExporter(DdlDialect.POSTGRES, dropExisting = true).render(m)
        val dropTable = out.indexOf("DROP TABLE")
        val dropSeq = out.indexOf("DROP SEQUENCE")
        val createSeq = out.indexOf("CREATE SEQUENCE")
        val createTable = out.indexOf("CREATE TABLE")
        assertTrue(dropTable in 0..<dropSeq, "DROP TABLE must come before DROP SEQUENCE")
        assertTrue(dropSeq < createSeq, "CREATE SEQUENCE must come after DROP SEQUENCE")
        assertTrue(createSeq < createTable, "CREATE TABLE must come after CREATE SEQUENCE")
    }

    @Test
    fun `dropExisting on Oracle wraps DROP in PL_SQL block`() {
        val m = model(listOf(ent("com.example.User", listOf(
            col("id", "java.lang.Long", pk = true, nullable = false)
        ))))
        val out = DdlExporter(DdlDialect.ORACLE, dropExisting = true).render(m)
        assertContains(out, "BEGIN")
        assertContains(out, "EXECUTE IMMEDIATE 'DROP TABLE")
        assertContains(out, "SQLCODE != -942")
    }

