    @Test
    fun `SINGLE_TABLE inheritance merges children into root with discriminator`() {
        val animal = ent("com.example.Animal",
            columns = listOf(
                col("id", "java.lang.Long", pk = true, nullable = false),
                col("name", "java.lang.String", length = 50)
            ),
            inheritance = ExportInheritance(strategy = "SINGLE_TABLE")
        )
        val dog = ent("com.example.Dog",
            columns = listOf(
                col("barkLoudness", "java.lang.Integer", columnName = "bark_loudness")
            ),
            inheritance = ExportInheritance(strategy = "SINGLE_TABLE", discriminatorValue = "DOG")
        )
        val out = DdlExporter(DdlDialect.POSTGRES).render(model(
            listOf(animal, dog),
            listOf(extendsRel("com.example.Dog", "com.example.Animal"))
        ))
        assertContains(out, "CREATE TABLE \"animal\"")
        assertContains(out, "\"bark_loudness\" INTEGER")
        // discriminator (snake_case ON: DTYPE → dtype)
        assertContains(out, "\"dtype\" VARCHAR(31)")
        assertFalse("CREATE TABLE \"dog\"" in out, "SINGLE_TABLE 자식은 별도 테이블을 만들면 안됨")
    }

    @Test
    fun `FK pointing at SINGLE_TABLE child is redirected to root with inherited type`() {
        val animal = ent("com.example.Animal",
            columns = listOf(col("id", "java.lang.Long", pk = true, nullable = false)),
            inheritance = ExportInheritance(strategy = "SINGLE_TABLE")
        )
        val dog = ent("com.example.Dog",
            columns = emptyList(),
            inheritance = ExportInheritance(strategy = "SINGLE_TABLE", discriminatorValue = "DOG")
        )
        val owner = ent("com.example.Owner", listOf(
            col("id", "java.lang.Long", pk = true, nullable = false),
            col("dog", "com.example.Dog", fk = "com.example.Dog", columnName = "dog_id")
        ))
        val out = DdlExporter(DdlDialect.POSTGRES).render(model(
            listOf(animal, dog, owner),
            listOf(extendsRel("com.example.Dog", "com.example.Animal"))
        ))
        // FK 컬럼 타입: 자식(Dog) 가 자체 PK 가 없어도 root(Animal) 의 BIGINT 를 빌려옴
        assertContains(out, "\"dog_id\" BIGINT")
        // FK ALTER: 자식이 아니라 root 테이블을 참조
        val fkLine = out.lines().first { it.contains("FOREIGN KEY") }
        assertContains(fkLine, "REFERENCES \"animal\"")
        assertFalse("REFERENCES \"dog\"" in fkLine, "FK 타깃이 자식 테이블을 가리키면 안됨")
    }

