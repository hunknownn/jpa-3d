 * 각 테스트는 ExportModel 을 in-memory 로 빌드 → DdlExporter 실행 → SQL substring 검증.
 * 헤더 코멘트의 `generatedAt` 만 시간 의존이라 본문 substring 위주로만 어서트한다.
