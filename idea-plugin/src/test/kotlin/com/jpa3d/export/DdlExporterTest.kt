    private fun col(
        name: String,
        type: String = "java.lang.String",
        pk: Boolean = false,
        nullable: Boolean = true,
        unique: Boolean = false,
        indexed: Boolean = false,
        fk: String? = null,
        length: Int? = null,
        generated: String? = null,
        precision: Int? = null,
        scale: Int? = null,
        lob: Boolean = false,
        sequenceName: String? = null,
        columnName: String? = null,
        columnNameExplicit: Boolean = false
    ) = ExportColumn(
        name = name,
        columnName = columnName ?: name,
        columnNameExplicit = columnNameExplicit,
        javaType = type,
        primaryKey = pk,
        nullable = nullable,
        unique = unique,
        indexed = indexed,
        foreignKey = fk != null,
        fkTarget = fk,
        length = length,
        generatedValue = generated,
        precision = precision,
        scale = scale,
        lob = lob,
        sequenceName = sequenceName
    )

    private fun ent(
        fqn: String,
        columns: List<ExportColumn>,
        kind: String = "entity",
        tableName: String? = null,
        tableNameExplicit: Boolean = false,
        inheritance: ExportInheritance? = null,
        compositeIndexes: List<List<String>> = emptyList(),
        compositeUniques: List<List<String>> = emptyList()
    ): ExportEntity {
        val simple = fqn.substringAfterLast('.')
        return ExportEntity(
            fqn = fqn,
            name = simple,
            `package` = fqn.substringBeforeLast('.', ""),
            kind = kind,
            tableName = tableName ?: simple,
            tableNameExplicit = tableNameExplicit,
            inheritance = inheritance,
            columns = columns,
            compositeIndexes = compositeIndexes,
            compositeUniques = compositeUniques
        )
    }

    private fun extendsRel(child: String, parent: String) =
        ExportRelation(source = child, target = parent, type = "EXTENDS")

    private fun model(
        entities: List<ExportEntity>,
        relations: List<ExportRelation> = emptyList()
    ) = ExportModel(
        schemaVersion = 1,
        generatedAt = "2026-01-01T00:00:00Z",
        entities = entities,
        relations = relations
    )

