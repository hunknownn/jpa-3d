    // Oracle 30 자 식별자 제한
    // ===================================================================================

    @Test
    fun `Oracle truncates generated identifier names beyond 30 chars`() {
        val longTable = "very_long_table_name_that_exceeds_thirty_chars"
        val longCol = "very_long_column_name_too_for_testing"
        val m = model(listOf(ent("com.example.X",
            tableName = longTable,
            columns = listOf(
                col("id", "java.lang.Long", pk = true, nullable = false),
                col(longCol, "java.lang.String", indexed = true)
            )
        )))
        val out = DdlExporter(DdlDialect.ORACLE).render(m)
        val idxLine = out.lines().first { it.startsWith("CREATE INDEX") }
        val name = Regex("""CREATE INDEX "([^"]+)"""").find(idxLine)?.groupValues?.get(1)
            ?: error("could not parse index name from: $idxLine")
        assertTrue(name.length <= 30, "Oracle 식별자 '$name' (${name.length}자) 가 30자를 초과")
    }

    @Test
    fun `non-Oracle dialects do not truncate long identifiers`() {
        val longTable = "very_long_table_name_that_exceeds_thirty_chars"
        val longCol = "very_long_column_name_too_for_testing"
        val m = model(listOf(ent("com.example.X",
            tableName = longTable,
            columns = listOf(
                col("id", "java.lang.Long", pk = true, nullable = false),
                col(longCol, "java.lang.String", indexed = true)
            )
        )))
        val out = DdlExporter(DdlDialect.POSTGRES).render(m)
        val idxLine = out.lines().first { it.startsWith("CREATE INDEX") }
        val name = Regex("""CREATE INDEX "([^"]+)"""").find(idxLine)?.groupValues?.get(1)
            ?: error("could not parse")
        assertTrue(name.length > 30, "Postgres 는 truncate 하지 않아야 함")
    }

