    @Test
    fun `composite UNIQUE with camelCase columns gets snake_case applied consistently`() {
        // B1 회귀 테스트: 분석기가 그룹 케이스를 보존하고, DdlExporter 가 snake_case 일관 적용.
        // 잘못된 동작 시 컬럼은 first_name 인데 인덱스는 firstname 을 참조해 SQL 실행 실패.
        val m = model(listOf(ent("com.example.User",
            columns = listOf(
                col("id", "java.lang.Long", pk = true, nullable = false),
                col("firstName"),
                col("lastName")
            ),
            compositeUniques = listOf(listOf("firstName", "lastName"))
        )))
        val out = DdlExporter(DdlDialect.POSTGRES, snakeCase = true).render(m)
        // 컬럼 정의도 snake_case
        assertContains(out, "\"first_name\"")
        assertContains(out, "\"last_name\"")
        // 복합 인덱스도 같은 변환 적용
        assertContains(out, "(\"first_name\", \"last_name\")")
        // 변환 누락 시 나타날 잘못된 식별자가 없어야 함
        assertFalse("\"firstname\"" in out)
    }

