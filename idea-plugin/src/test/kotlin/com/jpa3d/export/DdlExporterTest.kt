    @Test
    fun `TABLE_PER_CLASS includes parent columns in each child table`() {
        val parent = ent("com.example.Animal",
            columns = listOf(
                col("id", "java.lang.Long", pk = true, nullable = false),
                col("name", "java.lang.String", length = 50)
            ),
            inheritance = ExportInheritance(strategy = "TABLE_PER_CLASS")
        )
        val child = ent("com.example.Dog",
            columns = listOf(col("barkLoudness", "java.lang.Integer", columnName = "bark_loudness")),
            inheritance = ExportInheritance(strategy = "TABLE_PER_CLASS")
        )
        val out = DdlExporter(DdlDialect.POSTGRES).render(model(
            listOf(parent, child),
            listOf(extendsRel("com.example.Dog", "com.example.Animal"))
        ))
        assertContains(out, "CREATE TABLE \"animal\"")
        assertContains(out, "CREATE TABLE \"dog\"")
        val dogStart = out.indexOf("CREATE TABLE \"dog\"")
        val dogEnd = out.indexOf(");", dogStart)
        val dogBlock = out.substring(dogStart, dogEnd)
        assertContains(dogBlock, "\"id\"")
        assertContains(dogBlock, "\"name\"")
        assertContains(dogBlock, "\"bark_loudness\"")
    }

